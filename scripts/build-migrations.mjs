// Bundles the SQL that drizzle-kit wrote (src/db/migrations/*.sql) into a TypeScript module, so Metro
// needs no .sql loader and the migration text ships inside the JS bundle. Run by `npm run db:generate`.
// `--check` fails if the committed index.ts is out of date (used by CI).
import { readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const dir = new URL('../src/db/migrations/', import.meta.url).pathname;
const journal = JSON.parse(readFileSync(join(dir, 'meta/_journal.json'), 'utf8'));
const entries = [...journal.entries].sort((a, b) => a.idx - b.idx);

const lines = [
  '// GENERATED by scripts/build-migrations.mjs from the drizzle-kit output. Do not edit by hand.',
  '// Run `npm run db:generate` after changing src/db/schema.ts.',
  '',
  'export const journal = ' + JSON.stringify(journal, null, 2) + ';',
  '',
  'export const migrations = {',
];
for (const e of entries) {
  const key = `m${String(e.idx).padStart(4, '0')}`;
  const file = readdirSync(dir).find((f) => f === `${e.tag}.sql`);
  if (!file) throw new Error(`missing SQL for migration ${e.tag}`);
  lines.push(`  ${key}: ${JSON.stringify(readFileSync(join(dir, file), 'utf8'))},`);
}
lines.push('};', '', 'export default { journal, migrations };', '');
const out = lines.join('\n');
const target = join(dir, 'index.ts');

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) {
    console.error('src/db/migrations/index.ts is out of date. Run `npm run db:generate`.');
    process.exit(1);
  }
  process.stdout.write('Migrations bundle is up to date.\n');
} else {
  writeFileSync(target, out);
  rmSync(join(dir, 'migrations.js'), { force: true });
  process.stdout.write(`Wrote ${target} (${entries.length} migration(s)).\n`);
}
