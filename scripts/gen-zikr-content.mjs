// Regenerates src/features/zikr/content/data.ts from the website's own zikr content, so the app never
// holds hand-typed religious text (CLAUDE.md rule 3). Reads the web repo (read-only) at a git ref through
// `git show`, loads the two TypeScript modules with Node's type stripping, and writes their data as is.
// Usage: npm run zikr:content [-- <web-ref>]   (default ref: main; web repo at ../bustandeen)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const ref = process.argv[2] ?? 'main';
const web = process.env.BUSTANDEEN_WEB ?? '../bustandeen';
const files = {
  lib: 'frontend/src/utils/zikrLibrary.ts',
  data: 'frontend/src/components/zikr/zikrCounterData.ts',
};
const show = (path) =>
  execFileSync('git', ['-C', web, 'show', `${ref}:${path}`], { encoding: 'utf8' });
const commit = execFileSync('git', ['-C', web, 'rev-parse', '--short', ref], {
  encoding: 'utf8',
}).trim();

const dir = mkdtempSync(join(tmpdir(), 'zikr-content-'));
try {
  writeFileSync(join(dir, 'zikrLibrary.ts'), show(files.lib));
  writeFileSync(join(dir, 'zikrCounterData.ts'), show(files.data));
  const lib = await import(join(dir, 'zikrLibrary.ts'));
  const data = await import(join(dir, 'zikrCounterData.ts'));

  const bnNames = {};
  const names = [
    ...lib.PREDEFINED_TYPES,
    ...lib.ZIKR_LIBRARY.flatMap((c) => c.items.map((i) => i.name)),
  ];
  for (const n of names) {
    const bn = lib.zikrDisplayName(n, 'bn');
    if (bn !== n) bnNames[n] = bn;
  }
  const meanings = Object.fromEntries(
    Object.entries(data.DEFAULT_MEANINGS).map(([k, v]) => [
      k,
      { arabic: v.arabic, transliteration: v.translitFallback, meaningKey: v.meaningKey },
    ])
  );
  // References, grades and virtues are left out until each citation is verified (owner, 2026-11-25).
  const library = lib.ZIKR_LIBRARY.map((c) => ({
    id: c.id,
    title: c.title,
    titleBn: c.titleBn,
    blurb: c.blurb,
    blurbBn: c.blurbBn,
    items: c.items.map((i) =>
      Object.fromEntries(
        Object.entries({
          name: i.name,
          arabic: i.arabic,
          shortArabic: i.shortArabic,
          transliteration: i.transliteration,
          meaning: i.meaning,
          meaningBn: i.meaningBn,
          shortMeaning: i.shortMeaning,
        }).filter(([, v]) => v !== undefined)
      )
    ),
  }));
  const q = (v) => JSON.stringify(v);
  const out = `// GENERATED by scripts/gen-zikr-content.mjs from web ${ref} (${commit}). Do not edit by hand: change the
// website's content, then run \`npm run zikr:content\`. Religious text is copied verbatim (CLAUDE.md rule 3).
// Sources: web \`${files.lib}\` (PREDEFINED_TYPES, CORE_ZIKR, zikrDisplayName, ZIKR_LIBRARY) and
// \`${files.data}\` (DEFAULT_MEANINGS). References, grades and virtues are left out until each citation
// is verified (owner, 2026-11-25).

export interface CounterMeaning {
  arabic: string;
  transliteration: string;
  /** i18n key (en and bn in src/locales), as on the web. */
  meaningKey: string;
}

export interface LibraryItem {
  /** The counter key (the server's zikr type name). */
  name: string;
  /** Full Arabic. */
  arabic: string;
  /** Compact Arabic for the counter card; falls back to \`arabic\`. */
  shortArabic?: string;
  transliteration?: string;
  meaning: string;
  meaningBn?: string;
  /** Compact meaning for the counter card; falls back to \`meaning\`. */
  shortMeaning?: string;
}

export interface LibraryCategory {
  id: string;
  title: string;
  titleBn?: string;
  blurb: string;
  blurbBn?: string;
  items: LibraryItem[];
}

/** The counter's built-in zikr, in the web's order. */
export const PREDEFINED_TYPES: readonly string[] = ${q(lib.PREDEFINED_TYPES)};

/** Built-in zikr that cannot be removed (the salat tracker writes into them on the web). */
export const CORE_ZIKR: readonly string[] = ${q(lib.CORE_ZIKR)};

export const TAHLIL_NAME = ${q(lib.TAHLIL_NAME)};

/** Bangla display names (the web's zikrDisplayName). */
export const ZIKR_DISPLAY_BN: Readonly<Record<string, string>> = ${q(bnNames)};

/** What the counter card shows for the built-in zikr (the web's DEFAULT_MEANINGS). */
export const DEFAULT_MEANINGS: Readonly<Record<string, CounterMeaning>> = ${q(meanings)};

/** The curated library, by category. */
export const ZIKR_LIBRARY: readonly LibraryCategory[] = ${q(library)};
`;
  writeFileSync('src/features/zikr/content/data.ts', out);
  execFileSync('npx', ['prettier', '--write', 'src/features/zikr/content/data.ts'], {
    stdio: 'ignore',
  });
  process.stdout.write(`Wrote src/features/zikr/content/data.ts from web ${ref} (${commit}).\n`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
